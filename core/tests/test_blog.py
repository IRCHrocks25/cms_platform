        self.tpl.html_source = (
            "<!doctype html><html><head><title>H</title></head><body>"
            "<div data-blog-strip></div><footer data-section='footer'></footer>"
            "</body></html>"
        )
        self.tpl.save()
        _post(self.tenant, "MarkedPost", featured=True, order=0)
        r = Client(HTTP_HOST="acme.localhost").get("/")
